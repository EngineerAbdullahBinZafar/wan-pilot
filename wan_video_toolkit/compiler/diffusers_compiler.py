"""
Diffusers Script Compiler for Wan-Video.
Generates standalone Python code using Hugging Face Diffusers pipeline with sequential CPU offloading
and tiled VAE decode.
"""

from .ir import WanGenerationPipelineIR


def compile_diffusers_script(ir: WanGenerationPipelineIR) -> str:
    """
    Compiles WanGenerationPipelineIR into a clean Hugging Face Diffusers Python script.
    """
    model_id = "Wan-AI/Wan2.1-T2V-14B-Diffusers"
    if "1.3b" in ir.model.lower():
        model_id = "Wan-AI/Wan2.1-T2V-1.3B-Diffusers"
    elif "i2v" in ir.task or ir.input_image:
        model_id = "Wan-AI/Wan2.1-I2V-14B-720P-Diffusers"

    code_lines = [
        '"""',
        'Wan-Video Standalone Generation Script via Hugging Face Diffusers.',
        'Generated by wan-pilot compiler.',
        '"""',
        'import torch',
        'from diffusers import WanPipeline',
        'from diffusers.utils import export_to_video',
        '',
        'def main():',
        f'    prompt = "{ir.prompt}"',
        f'    negative_prompt = "{ir.negative_prompt}"',
        f'    model_id = "{model_id}"',
        '',
        '    print(f"Loading pipeline {model_id} in bfloat16...")',
        '    pipe = WanPipeline.from_pretrained(',
        '        model_id,',
        '        torch_dtype=torch.bfloat16,',
        '        device_map="auto",',
        '    )',
        '',
        '    # Memory optimizations for consumer GPUs',
        '    pipe.enable_model_cpu_offload()',
        '    if hasattr(pipe, "vae") and hasattr(pipe.vae, "enable_tiling"):',
        '        pipe.vae.enable_tiling()',
        '',
        '    print("Generating video...")',
        '    output = pipe(',
        '        prompt=prompt,',
        '        negative_prompt=negative_prompt,',
        f'        height={ir.height},',
        f'        width={ir.width},',
        f'        num_frames={ir.num_frames},',
        f'        guidance_scale={ir.guidance},',
        f'        num_inference_steps={ir.steps},',
    ]

    if ir.seed >= 0:
        code_lines.append(f'        generator=torch.Generator(device="cuda").manual_seed({ir.seed}),')

    code_lines.extend([
        '    )',
        '',
        '    video_frames = output.frames[0]',
        '    output_path = "wan_generation_output.mp4"',
        f'    export_to_video(video_frames, output_path, fps={ir.fps})',
        '    print(f"Video saved successfully to {output_path}")',
        '',
        'if __name__ == "__main__":',
        '    main()',
    ])

    return "\n".join(code_lines)
