"""
CLI Script Compiler for Wan-Video.
Generates production-grade Bash and PowerShell execution scripts with official Wan arguments
and optimized offloading flags.
"""

from .ir import WanGenerationPipelineIR, TargetFormat


def _determine_task_arg(ir: WanGenerationPipelineIR) -> str:
    """Computes the official Wan --task argument (e.g., t2v-14B, i2v-14B, t2v-1.3B)."""
    prefix = "i2v" if ir.input_image or ir.task == "i2v" else "t2v"
    if "1.3b" in ir.model.lower():
        size = "1.3B"
    elif "moe" in ir.model.lower() or "14b" in ir.model.lower():
        size = "14B"
    elif "27b" in ir.model.lower():
        size = "27B"
    else:
        size = "14B"
    return f"{prefix}-{size}"


def compile_cli_script(ir: WanGenerationPipelineIR, target_format: TargetFormat = TargetFormat.CLI_BASH) -> str:
    """
    Compiles WanGenerationPipelineIR into a standalone shell execution script.
    """
    task_arg = _determine_task_arg(ir)
    size_arg = f"{ir.width}*{ir.height}"
    flags = ir.get_recommended_flags()

    # Base arguments list
    args = [
        f"--task {task_arg}",
        f"--size {size_arg}",
        f"--prompt \"{ir.prompt}\"",
    ]

    if ir.negative_prompt:
        args.append(f"--negative_prompt \"{ir.negative_prompt}\"")

    if ir.input_image:
        args.append(f"--image \"{ir.input_image}\"")

    if ir.steps:
        args.append(f"--steps {ir.steps}")

    if ir.guidance:
        args.append(f"--sample_guide_scale {ir.guidance}")

    if ir.seed >= 0:
        args.append(f"--seed {ir.seed}")

    for flag in flags:
        args.append(flag)

    if target_format == TargetFormat.CLI_POWERSHELL or str(target_format).lower().endswith("powershell"):
        # PowerShell format
        continuation = " `"
        lines = [
            "# Wan-Video Automated Generation Script (PowerShell)",
            "# Generated by wan-pilot compiler",
            "$env:CUDA_VISIBLE_DEVICES = \"0\"",
            "$env:PYTORCH_CUDA_ALLOC_CONF = \"expandable_segments:True\"",
            "",
            f"python generate.py{continuation}",
        ]
        for i, arg in enumerate(args):
            is_last = (i == len(args) - 1)
            suffix = "" if is_last else continuation
            lines.append(f"  {arg}{suffix}")
        return "\n".join(lines)
    else:
        # Bash format
        continuation = " \\"
        lines = [
            "#!/usr/bin/env bash",
            "# Wan-Video Automated Generation Script (Bash)",
            "# Generated by wan-pilot compiler",
            "set -euo pipefail",
            "export CUDA_VISIBLE_DEVICES=0",
            "export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True",
            "",
            f"python generate.py{continuation}",
        ]
        for i, arg in enumerate(args):
            is_last = (i == len(args) - 1)
            suffix = "" if is_last else continuation
            lines.append(f"  {arg}{suffix}")
        return "\n".join(lines)
